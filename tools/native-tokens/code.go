package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"math"
	"os"
	"path/filepath"
	"strings"
)

type codeAsset struct {
	Name        string            `json:"name"`
	Type        string            `json:"type"`
	Colors      map[string]string `json:"colors"`
	TokenColors []struct {
		Scope    json.RawMessage `json:"scope"`
		Settings struct {
			Foreground string `json:"foreground"`
			FontStyle  string `json:"fontStyle"`
		} `json:"settings"`
	} `json:"tokenColors"`
}

// Representative TextMate scopes map the vendored theme colors to MyGo's
// coarser Go tokenizer categories. This is a color port, not a TextMate runtime.
var nativeScopes = []struct{ kind, scope string }{
	{"TokenKeyword", "keyword"}, {"TokenOperator", "keyword.operator"},
	{"TokenType", "entity.name.type"}, {"TokenFunction", "entity.name.function"},
	{"TokenVariable", "variable.parameter.function"}, {"TokenProperty", "variable.other.property"},
	{"TokenConstant", "constant"}, {"TokenNumber", "constant.numeric"},
	{"TokenString", "string"}, {"TokenEscape", "constant.character.escape"},
	{"TokenRegexp", "string.regexp"}, {"TokenComment", "comment"},
	{"TokenPunctuation", "punctuation"}, {"TokenTag", "entity.name.tag"},
	{"TokenAttribute", "entity.other.attribute-name"}, {"TokenMeta", "meta.preprocessor"},
	{"TokenHeading", "markup.heading"}, {"TokenLink", "markup.underline.link"},
	{"TokenCode", "markup.inline.raw"}, {"TokenInserted", "markup.inserted"},
	{"TokenDeleted", "markup.deleted"}, {"TokenInvalid", "invalid"},
}

func codeOutput(root string, check bool) error {
	var out bytes.Buffer
	out.WriteString("// Code generated by go run ./tools/native-tokens; DO NOT EDIT.\n// Color data: Pierre theme 2.0.0 (Apache-2.0), Shiki themes 4.4.3 (MIT).\n// Provenance and complete notices: tools/native-tokens/themes.\npackage design\nimport (\"github.com/egoist/mygo/ui\"; \"github.com/egoist/mygo/ui/editor\")\n")
	out.WriteString("var generatedCodeThemes = map[string]editor.Theme{\n")
	for _, name := range []string{"pierre-light", "pierre-dark", "github-light", "github-dark", "vitesse-light", "vitesse-dark"} {
		data, err := os.ReadFile(filepath.Join(root, "tools/native-tokens/themes", name+".json"))
		if err != nil {
			return err
		}
		var asset codeAsset
		if err := json.Unmarshal(data, &asset); err != nil {
			return err
		}
		if asset.Name != name || (asset.Type != "light" && asset.Type != "dark") {
			return fmt.Errorf("invalid native code asset %s", name)
		}
		bg, fg := asset.Colors["editor.background"], asset.Colors["editor.foreground"]
		for _, c := range []string{bg, fg} {
			if _, err := color(c, nil, map[string]bool{}); err != nil {
				return err
			}
		}
		fmt.Fprintf(&out, "%q: {Background:ui.Hex(%q), Text:ui.Hex(%q), Tokens:[editor.TokenInvalid+1]editor.TokenStyle{\n", name, bg, fg)
		for _, mapping := range nativeScopes {
			best, foreground, style := -1, fg, ""
			for _, rule := range asset.TokenColors {
				var scopes []string
				if len(rule.Scope) == 0 {
					continue
				}
				if rule.Scope[0] == '"' {
					var single string
					if err := json.Unmarshal(rule.Scope, &single); err != nil {
						return err
					}
					scopes = strings.Split(single, ",")
				} else if err := json.Unmarshal(rule.Scope, &scopes); err != nil {
					return err
				}
				for _, scope := range scopes {
					scope = strings.TrimSpace(scope)
					if scope == "" || !(mapping.scope == scope || strings.HasPrefix(mapping.scope, scope+".")) || len(scope) < best {
						continue
					}
					if rule.Settings.Foreground != "" {
						foreground = rule.Settings.Foreground
					}
					style = rule.Settings.FontStyle
					best = len(scope)
				}
			}
			if _, err := color(foreground, nil, map[string]bool{}); err != nil {
				return fmt.Errorf("asset %s %s: %w", name, mapping.kind, err)
			}
			ink, _ := color(foreground, nil, map[string]bool{})
			canvas, _ := color(bg, nil, map[string]bool{})
			ink = readable(ink, canvas)
			foreground = fmt.Sprintf("#%02x%02x%02x", rounded(ink.r), rounded(ink.g), rounded(ink.b))
			fmt.Fprintf(&out, "editor.%s:{Color:ui.Hex(%q),Italic:%t,Bold:%t},\n", mapping.kind, foreground, strings.Contains(style, "italic"), strings.Contains(style, "bold"))
		}
		out.WriteString("}},\n")
	}
	out.WriteString("}\n")
	return output(root, "apps/desktop/internal/design/code_generated.go", out.Bytes(), check)
}

func luminance(c rgba) float64 {
	linear := func(v float64) float64 {
		v /= 255
		if v <= .04045 {
			return v / 12.92
		}
		return math.Pow((v+.055)/1.055, 2.4)
	}
	return .2126*linear(c.r) + .7152*linear(c.g) + .0722*linear(c.b)
}
func ratio(a, b rgba) float64 {
	x, y := luminance(a), luminance(b)
	return (max(x, y) + .05) / (min(x, y) + .05)
}

// readable preserves the rendered source color where it meets AA. Otherwise
// find the smallest sRGB mix toward black/white that meets 4.5:1 after rounding.
// The source JSON remains unchanged; only the coarse native color port is tuned.
func readable(ink, canvas rgba) rgba {
	a := ink.a / 255
	quantize := func(c rgba) rgba {
		return rgba{float64(rounded(c.r)), float64(rounded(c.g)), float64(rounded(c.b)), 255}
	}
	ink = quantize(rgba{ink.r*a + canvas.r*(1-a), ink.g*a + canvas.g*(1-a), ink.b*a + canvas.b*(1-a), 255})
	if ratio(ink, canvas) >= 4.5 {
		return ink
	}
	black, white := rgba{0, 0, 0, 255}, rgba{255, 255, 255, 255}
	target := black
	if ratio(white, canvas) > ratio(black, canvas) {
		target = white
	}
	mix := func(p float64) rgba {
		return quantize(rgba{ink.r + (target.r-ink.r)*p, ink.g + (target.g-ink.g)*p, ink.b + (target.b-ink.b)*p, 255})
	}
	lo, hi := float64(0), float64(1)
	for range 20 {
		mid := (lo + hi) / 2
		if ratio(mix(mid), canvas) >= 4.5 {
			hi = mid
		} else {
			lo = mid
		}
	}
	return mix(hi)
}
