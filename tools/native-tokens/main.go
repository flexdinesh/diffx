// native-tokens compiles the canonical UI tokens to Go. It is not a runtime dependency.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"
	"text/scanner"
)

type choice struct{ ID, Label, Kind, Mode string }
type rule struct {
	selector string
	vars     map[string]string
}
type rgba struct{ r, g, b, a float64 }

var comments = regexp.MustCompile(`(?s)/\*.*?\*/`)
var paletteID = regexp.MustCompile(`data-palette="([a-z0-9-]+)"`)
var paletteSelector = regexp.MustCompile(`^(?::root)?\[data-palette="[a-z0-9-]+"\]$`)

func main() {
	check := flag.Bool("check", false, "fail if generated Go differs")
	root := flag.String("root", ".", "repository root")
	flag.Parse()
	if err := generate(*root, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(root string, check bool) error {
	read := func(path string) ([]byte, error) { return os.ReadFile(filepath.Join(root, path)) }
	ts, err := read("apps/web/src/theme.ts")
	if err != nil {
		return err
	}
	choices, err := registry(string(ts))
	if err != nil {
		return err
	}
	css, err := read("packages/ui/src/tokens.css")
	if err != nil {
		return err
	}
	rules, err := stylesheet(string(css))
	if err != nil {
		return err
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by go run ./tools/native-tokens; DO NOT EDIT.\npackage design\n\n")
	out.WriteString("var Themes = []ThemeChoice{\n")
	for _, c := range choices {
		fmt.Fprintf(&out, "{ID:%q,Label:%q,Kind:%q,Mode:%q},\n", c.ID, c.Label, c.Kind, c.Mode)
	}
	out.WriteString("}\nvar generatedPalettes = map[string]tokenSet{\n")
	for _, c := range choices {
		if c.ID == "system" {
			continue
		}
		vars, err := cascade(rules, c)
		if err != nil {
			return err
		}
		fmt.Fprintf(&out, "%q: {dark:%t, colors:map[string]uint32{\n", c.ID, c.Mode == "dark")
		keys := sortedKeys(vars)
		for _, k := range keys {
			if !colorToken(k) {
				continue
			}
			v, err := resolveColor(k, vars, map[string]bool{})
			if err != nil {
				return fmt.Errorf("%s --%s: %w", c.ID, k, err)
			}
			pack := uint32(rounded(v.r))<<24 | uint32(rounded(v.g))<<16 | uint32(rounded(v.b))<<8 | uint32(rounded(v.a))
			fmt.Fprintf(&out, "%q:0x%08x,\n", k, pack)
		}
		out.WriteString("},metrics:map[string]float32{\n")
		for _, k := range keys {
			if !metricToken(k) {
				continue
			}
			v, err := resolveMetric(k, vars, map[string]bool{})
			if err != nil {
				return fmt.Errorf("--%s: %w", k, err)
			}
			fmt.Fprintf(&out, "%q:%s,\n", k, strconv.FormatFloat(v, 'f', -1, 32))
		}
		out.WriteString("}},\n")
	}
	out.WriteString("}\n")
	if err := output(root, "apps/desktop/internal/design/tokens_generated.go", out.Bytes(), check); err != nil {
		return err
	}
	var ids bytes.Buffer
	ids.WriteString("// Code generated by go run ./tools/native-tokens; DO NOT EDIT.\npackage preferences\nvar themeIDs = map[string]bool{\n")
	for _, c := range choices {
		fmt.Fprintf(&ids, "%q:true,\n", c.ID)
	}
	ids.WriteString("}\n")
	base, err := cascade(rules, choice{ID: "light", Mode: "light", Kind: "base"})
	if err != nil {
		return err
	}
	for _, metric := range []struct{ token, name string }{{"streams-width", "defaultProjectPaneWidth"}, {"sidebar-width", "defaultFilePaneWidth"}} {
		value, err := resolveMetric(metric.token, base, map[string]bool{})
		if err != nil {
			return err
		}
		fmt.Fprintf(&ids, "const %s float32 = %s\n", metric.name, strconv.FormatFloat(value, 'f', -1, 32))
	}
	if err := output(root, "apps/desktop/internal/preferences/themes_generated.go", ids.Bytes(), check); err != nil {
		return err
	}
	return codeOutput(root, check)
}

func output(root, path string, data []byte, check bool) error {
	data, err := format.Source(data)
	if err != nil {
		return err
	}
	path = filepath.Join(root, path)
	if check {
		current, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.Equal(current, data) {
			return fmt.Errorf("native token drift: %s; run go run ./tools/native-tokens", path)
		}
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	return os.WriteFile(path, data, 0644)
}

// registry accepts only literal registry entries and the three current code
// selectors. Expressions in identity, mode or label must fail, never disappear.
func registry(src string) ([]choice, error) {
	_, src, ok := strings.Cut(src, "export const THEMES = [")
	if !ok {
		return nil, errors.New("THEMES array missing")
	}
	var s scanner.Scanner
	s.Init(strings.NewReader(src))
	s.Mode = scanner.ScanIdents | scanner.ScanStrings | scanner.SkipComments | scanner.ScanComments
	var scanErr error
	s.Error = func(_ *scanner.Scanner, msg string) { scanErr = errors.New(msg) }
	next := func() string { s.Scan(); return s.TokenText() }
	tok := next()
	var result []choice
	seen := map[string]bool{}
	for tok != "]" {
		if tok != "{" {
			return nil, fmt.Errorf("registry: expected object, got %q", tok)
		}
		values := map[string]string{}
		for tok = next(); tok != "}"; {
			key := tok
			if !slices.Contains([]string{"id", "label", "kind", "mode", "code"}, key) {
				return nil, fmt.Errorf("registry: unsupported property %q", key)
			}
			if _, ok := values[key]; ok {
				return nil, fmt.Errorf("registry: duplicate %s", key)
			}
			if next() != ":" {
				return nil, errors.New("registry: expected colon")
			}
			tok = next()
			if key == "code" {
				if tok == "bundled" {
					if next() != "(" {
						return nil, errors.New("registry: bundled expects literal")
					}
					if _, err := strconv.Unquote(next()); err != nil {
						return nil, errors.New("registry: bundled expects string")
					}
					if next() != ")" {
						return nil, errors.New("registry: bundled expression unsupported")
					}
				} else if tok != "pierre" && tok != "palette" {
					return nil, fmt.Errorf("registry: code expression %q unsupported", tok)
				}
				values[key] = tok
			} else {
				value, err := strconv.Unquote(tok)
				if err != nil {
					return nil, fmt.Errorf("registry %s: literal string required", key)
				}
				values[key] = value
			}
			tok = next()
			if tok == "," {
				tok = next()
			} else if tok != "}" {
				return nil, fmt.Errorf("registry: expression after %s unsupported", key)
			}
		}
		c := choice{values["id"], values["label"], values["kind"], values["mode"]}
		if c.ID == "" || c.Label == "" || !slices.Contains([]string{"base", "palette"}, c.Kind) || !slices.Contains([]string{"system", "light", "dark"}, c.Mode) || len(values) != 5 || seen[c.ID] {
			return nil, fmt.Errorf("invalid theme entry %+v", c)
		}
		seen[c.ID] = true
		result = append(result, c)
		tok = next()
		if tok == "," {
			tok = next()
		} else if tok != "]" {
			return nil, errors.New("registry: expected comma")
		}
	}
	if scanErr != nil {
		return nil, scanErr
	}
	if len(result) == 0 || result[0].ID != "system" {
		return nil, errors.New("registry: system must be first")
	}
	return result, nil
}

func stylesheet(src string) ([]rule, error) {
	src = comments.ReplaceAllString(src, "")
	var rules []rule
	for strings.TrimSpace(src) != "" {
		selector, tail, ok := strings.Cut(src, "{")
		if !ok {
			return nil, errors.New("CSS: missing block")
		}
		depth, end := 1, 0
		for ; end < len(tail) && depth > 0; end++ {
			switch tail[end] {
			case '{':
				depth++
			case '}':
				depth--
			}
		}
		if depth != 0 {
			return nil, errors.New("CSS: unclosed block")
		}
		body := tail[:end-1]
		src = tail[end:]
		selector = strings.TrimSpace(selector)
		// Native window sizing does not use browser viewport/pointer queries.
		if strings.HasPrefix(selector, "@media ") {
			nested, err := stylesheet(body)
			if err != nil {
				return nil, err
			}
			for _, r := range nested {
				for k := range r.vars {
					if colorToken(k) {
						return nil, fmt.Errorf("CSS: conditional color --%s needs an explicit native translation", k)
					}
				}
			}
			continue
		}
		if strings.ContainsAny(body, "{}") || strings.HasPrefix(selector, "@") {
			return nil, fmt.Errorf("CSS: unsupported rule %q", selector)
		}
		for _, part := range strings.Split(selector, ",") {
			part = strings.TrimSpace(part)
			if part != ":root" && part != `:root[data-theme="dark"]` && !paletteSelector.MatchString(part) {
				return nil, fmt.Errorf("CSS: unsupported token selector %q", part)
			}
		}
		vars := map[string]string{}
		for _, decl := range strings.Split(body, ";") {
			decl = strings.TrimSpace(decl)
			if decl == "" {
				continue
			}
			key, value, ok := strings.Cut(decl, ":")
			if !ok {
				return nil, fmt.Errorf("CSS: invalid declaration %q", decl)
			}
			key, value = strings.TrimSpace(key), strings.TrimSpace(value)
			if key == "color-scheme" {
				vars[key] = value
			} else if strings.HasPrefix(key, "--") {
				vars[strings.TrimPrefix(key, "--")] = value
			} else {
				return nil, fmt.Errorf("CSS: unsupported declaration %q", key)
			}
		}
		rules = append(rules, rule{selector, vars})
	}
	return rules, nil
}

func cascade(rules []rule, c choice) (map[string]string, error) {
	vars := map[string]string{}
	apply := func(r rule) {
		for k, v := range r.vars {
			vars[k] = v
		}
	}
	for _, r := range rules {
		if strings.Contains(r.selector, "[data-palette=\"diffx-light\"]") {
			apply(r)
		}
	}
	if c.Mode == "dark" {
		for _, r := range rules {
			if strings.Contains(r.selector, "[data-palette=\"diffx-dark\"]") {
				apply(r)
			}
		}
	}
	if c.Kind == "palette" {
		found := false
		for _, r := range rules {
			for _, m := range paletteID.FindAllStringSubmatch(r.selector, -1) {
				if m[1] == c.ID {
					apply(r)
					found = true
					break
				}
			}
		}
		if !found {
			return nil, fmt.Errorf("palette CSS missing: %s", c.ID)
		}
	}
	if vars["color-scheme"] != c.Mode {
		return nil, fmt.Errorf("palette mode disagrees with registry: %s", c.ID)
	}
	return vars, nil
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys
}
func colorToken(k string) bool {
	return slices.Contains([]string{"bg", "panel", "shell-canvas", "surface-raised", "fg", "text-secondary", "muted", "border", "border-muted", "border-control", "hover", "shell-hover", "count-bg", "diff-file-header", "diff-canvas", "diff-canvas-dot", "accent", "accent-hover", "accent-bg", "on-accent", "review-anchor", "backdrop", "focus-outline-color", "scrollbar-thumb", "scrollbar-thumb-hover", "scrollbar-thumb-active"}, k) || strings.HasPrefix(k, "success") || strings.HasPrefix(k, "warning") || strings.HasPrefix(k, "error") || strings.HasPrefix(k, "file-") || strings.HasPrefix(k, "diffs-")
}
func metricToken(k string) bool {
	return strings.HasPrefix(k, "space-") || slices.Contains([]string{"radius-xs", "radius-sm", "radius-md", "radius-lg", "radius-control", "focus-outline-width", "focus-outline-offset", "scrollbar-size", "scrollbar-thumb-inset", "control-height", "control-compact", "control-small", "control-large", "touch-target", "topbar-height", "panel-header-height", "statusbar-height", "page-gutter", "diff-gutter", "shell-gutter", "sidebar-width", "streams-width", "activity-item", "activity-width", "reading-width"}, k)
}
func rounded(v float64) uint8 { return uint8(max(0, min(255, v)) + 0.5) }

func resolveColor(k string, vars map[string]string, visiting map[string]bool) (rgba, error) {
	if visiting[k] {
		return rgba{}, fmt.Errorf("cyclic variable --%s", k)
	}
	v, ok := vars[k]
	if !ok {
		return rgba{}, fmt.Errorf("missing variable --%s", k)
	}
	visiting[k] = true
	defer delete(visiting, k)
	return color(v, vars, visiting)
}
func color(v string, vars map[string]string, visiting map[string]bool) (rgba, error) {
	v = strings.TrimSpace(v)
	if v == "transparent" {
		return rgba{}, nil
	}
	if strings.HasPrefix(v, "var(--") && strings.HasSuffix(v, ")") {
		return resolveColor(v[6:len(v)-1], vars, visiting)
	}
	if strings.HasPrefix(v, "#") {
		h := v[1:]
		if len(h) == 3 || len(h) == 4 {
			var b strings.Builder
			for _, c := range h {
				b.WriteRune(c)
				b.WriteRune(c)
			}
			h = b.String()
		}
		if len(h) == 6 {
			h += "ff"
		}
		if len(h) != 8 {
			return rgba{}, fmt.Errorf("unsupported color %q", v)
		}
		n, err := strconv.ParseUint(h, 16, 32)
		if err != nil {
			return rgba{}, err
		}
		return rgba{float64(n >> 24), float64(n >> 16 & 255), float64(n >> 8 & 255), float64(n & 255)}, nil
	}
	if strings.HasPrefix(v, "color-mix(in srgb,") && strings.HasSuffix(v, ")") {
		parts := splitArgs(strings.TrimSuffix(strings.TrimPrefix(v, "color-mix(in srgb,"), ")"))
		if len(parts) != 2 {
			return rgba{}, fmt.Errorf("unsupported mix %q", v)
		}
		first := strings.Fields(strings.TrimSpace(parts[0]))
		if len(first) < 2 {
			return rgba{}, fmt.Errorf("mix percentage required: %s", v)
		}
		pct := first[len(first)-1]
		if !strings.HasSuffix(pct, "%") {
			return rgba{}, fmt.Errorf("mix percentage required: %s", v)
		}
		p, err := strconv.ParseFloat(strings.TrimSuffix(pct, "%"), 64)
		if err != nil || p < 0 || p > 100 {
			return rgba{}, fmt.Errorf("invalid mix percentage: %s", v)
		}
		a, err := color(strings.Join(first[:len(first)-1], " "), vars, visiting)
		if err != nil {
			return rgba{}, err
		}
		b, err := color(parts[1], vars, visiting)
		if err != nil {
			return rgba{}, err
		}
		p /= 100
		alpha := a.a*p + b.a*(1-p)
		if alpha == 0 {
			return rgba{}, nil
		}
		mix := func(x, y float64) float64 { return (x*a.a*p + y*b.a*(1-p)) / alpha }
		return rgba{mix(a.r, b.r), mix(a.g, b.g), mix(a.b, b.b), alpha}, nil
	}
	return rgba{}, fmt.Errorf("unsupported color expression %q", v)
}
func splitArgs(s string) []string {
	var result []string
	depth, start := 0, 0
	for i, c := range s {
		switch c {
		case '(':
			depth++
		case ')':
			depth--
		case ',':
			if depth == 0 {
				result = append(result, s[start:i])
				start = i + 1
			}
		}
	}
	return append(result, s[start:])
}

func resolveMetric(k string, vars map[string]string, visiting map[string]bool) (float64, error) {
	if visiting[k] {
		return 0, fmt.Errorf("cyclic metric --%s", k)
	}
	v, ok := vars[k]
	if !ok {
		return 0, fmt.Errorf("missing metric --%s", k)
	}
	visiting[k] = true
	defer delete(visiting, k)
	return metric(v, vars, visiting)
}
func metric(v string, vars map[string]string, visiting map[string]bool) (float64, error) {
	v = strings.TrimSpace(v)
	if strings.HasPrefix(v, "var(--") && strings.HasSuffix(v, ")") {
		return resolveMetric(v[6:len(v)-1], vars, visiting)
	}
	if strings.HasPrefix(v, "calc(") && strings.HasSuffix(v, ")") {
		return arithmetic(v[5:len(v)-1], vars, visiting)
	}
	mult := float64(1)
	if strings.HasSuffix(v, "rem") {
		mult = 16
		v = strings.TrimSuffix(v, "rem")
	} else {
		v = strings.TrimSuffix(v, "px")
	}
	n, err := strconv.ParseFloat(v, 64)
	if err != nil {
		return 0, fmt.Errorf("unsupported metric expression %q", v)
	}
	return n * mult, nil
}
func arithmetic(v string, vars map[string]string, visiting map[string]bool) (float64, error) {
	// Only the canonical two-operand +/* expressions are supported. Fail closed
	// when new CSS arithmetic needs an intentional native translation.
	for _, op := range []string{" + ", " * ", " / "} {
		parts := strings.Split(v, op)
		if len(parts) == 1 {
			continue
		}
		if len(parts) != 2 {
			return 0, fmt.Errorf("unsupported arithmetic %q", v)
		}
		a, err := metric(parts[0], vars, visiting)
		if err != nil {
			return 0, err
		}
		b, err := arithmetic(parts[1], vars, visiting)
		if err != nil {
			return 0, err
		}
		switch op {
		case " + ":
			return a + b, nil
		case " * ":
			return a * b, nil
		case " / ":
			if b == 0 {
				return 0, errors.New("division by zero")
			}
			return a / b, nil
		}
	}
	return metric(v, vars, visiting)
}
